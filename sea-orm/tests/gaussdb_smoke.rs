//! GaussDB real-database smoke tests (T2).
//!
//! These are compiled with `--features gaussdb` but only touch the real
//! database when `GAUSSDB_PASSWORD` is set; without it every test prints
//! "skipped: GAUSSDB_PASSWORD not set" and exits successfully.
//!
//! Intended to be run by the controller against the local probe database:
//! `gaussdb://appuser:<GAUSSDB_PASSWORD>@localhost:5432/seaorm_survey`.

#![cfg(feature = "gaussdb")]

use sea_orm::{ConnectionTrait, Database, DbBackend, DbErr, Statement};

/// 连接守卫：取 GAUSSDB_PASSWORD；缺失则打印 skip 提示并返回 None（不 panic）。
fn gaussdb_password() -> Option<String> {
    match std::env::var("GAUSSDB_PASSWORD") {
        Ok(pwd) => Some(pwd),
        Err(_) => {
            eprintln!("skipped: GAUSSDB_PASSWORD not set");
            None
        }
    }
}

/// 探针库连接 URL（本地 5432，库 seaorm_survey，用户 appuser）。
fn gaussdb_url(pwd: &str) -> String {
    format!("gaussdb://appuser:{pwd}@localhost:5432/seaorm_survey")
}

#[tokio::test]
async fn connect_smoke() {
    let Some(pwd) = gaussdb_password() else {
        return;
    };
    let db = Database::connect(gaussdb_url(&pwd))
        .await
        .expect("connect gaussdb://");
    assert_eq!(db.get_database_backend(), DbBackend::GaussDB);
}

#[tokio::test]
async fn raw_query() {
    let Some(pwd) = gaussdb_password() else {
        return;
    };
    let db = Database::connect(gaussdb_url(&pwd))
        .await
        .expect("connect gaussdb://");
    let rows = db
        .query_all_raw(Statement::from_string(DbBackend::GaussDB, "SELECT 1"))
        .await
        .expect("SELECT 1");
    assert_eq!(rows.len(), 1);
}

#[tokio::test]
async fn support_returning() {
    assert!(DbBackend::GaussDB.support_returning());
}

#[tokio::test]
async fn insert_returning() {
    let Some(pwd) = gaussdb_password() else {
        return;
    };
    let db = Database::connect(gaussdb_url(&pwd))
        .await
        .expect("connect gaussdb://");

    // 唯一表名，避免并行运行 / 上次失败残留造成的冲突
    let table = format!(
        "seaorm_smoke_t_{}",
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .expect("system clock before Unix epoch")
            .as_nanos()
    );

    db.execute_unprepared(&format!(
        "CREATE TABLE {table} (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v varchar(10))"
    ))
    .await
    .expect("create smoke table");

    let body = async {
        // T4 已适配：GaussDB A 模式把 identity 主键的 RETURNING 列报告为 NUMERIC
        // （探针定档，见 probe/verification-results.md §六[3]），gaussdb 侧解码已支持
        // （QueryResult 标记 from_gaussdb + 整数 TryGetable 的 NUMERIC 兜底解码），
        // 去掉 ::text 绕道，直接正向断言整数解码成功。
        let stmt = Statement::from_string(
            DbBackend::GaussDB,
            format!("INSERT INTO {table} (v) VALUES ('hello') RETURNING id"),
        );
        let rows = db.query_all_raw(stmt).await.expect("INSERT .. RETURNING");
        assert_eq!(rows.len(), 1);
        let id: i64 = rows[0]
            .try_get_by("id")
            .expect("returned id (i64 direct decode)");
        assert!(id > 0);
        let id: i32 = rows[0]
            .try_get_by("id")
            .expect("returned id (i32 direct decode)");
        assert!(id > 0);
        Ok::<(), DbErr>(())
    }
    .await;

    // 无论 body 成败都清理临时表
    let dropped = db
        .execute_unprepared(&format!("DROP TABLE {table}"))
        .await
        .map(|_| ());

    body.expect("insert_returning body");
    dropped.expect("drop smoke table");
}
