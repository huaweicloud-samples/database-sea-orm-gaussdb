//! GaussDB 真库迁移链路 journey 测试（T10）。
//!
//! 与 `gaussdb_smoke.rs` 同构：`--features gaussdb` 编译，仅当
//! `GAUSSDB_PASSWORD` 设置时触碰真库；缺失则打印 skip 并成功退出。
//! 由 controller 对本地探针库执行：
//! `gaussdb://appuser:<GAUSSDB_PASSWORD>@localhost:5432/seaorm_survey`。
//!
//! 覆盖 sea-orm-migration 在 GaussDB A 模式的完整迁移链路：
//! `MigratorTrait::install`（seaql_migrations 建表）-> up（sea-query
//! `Table::create()` 渲染 DDL + 插初始行 + 写迁移记录）-> down
//! （DROP TABLE + 补清 identity 附属序列 + 删迁移记录）。
//!
//! 定档出处：survey/02 §类型定档表——A 模式 IDENTITY 附属序列命名
//! `{table}_{col}_identity`，`DROP TABLE` 不级联（残留序列重名致
//! 42P07），回滚清理须补 `DROP SEQUENCE`。

#![cfg(feature = "gaussdb")]

use sea_orm::{ConnectionTrait, Database, DbBackend, DbErr, Statement};
use sea_orm_migration::prelude::*;

// ---- 迁移定义 ----

#[derive(DeriveIden)]
enum SeaormMigT {
    Table,
    Id,
    Name,
}

#[derive(DeriveMigrationName)]
pub struct Migration;

#[async_trait::async_trait]
impl MigrationTrait for Migration {
    async fn up(&self, manager: &SchemaManager) -> Result<(), DbErr> {
        // identity 主键 + varchar 列，走 sea-query Table::create() 渲染链路
        // （GaussDB 后端渲染 `integer GENERATED BY DEFAULT AS IDENTITY`，
        // 见 survey/02：A 模式建表可用，临时表才禁 serial）
        manager
            .create_table(
                Table::create()
                    .table(SeaormMigT::Table)
                    .if_not_exists()
                    .col(
                        ColumnDef::new(SeaormMigT::Id)
                            .integer()
                            .not_null()
                            .auto_increment()
                            .primary_key(),
                    )
                    .col(ColumnDef::new(SeaormMigT::Name).string_len(64).not_null())
                    .to_owned(),
            )
            .await?;
        manager
            .get_connection()
            .execute_unprepared("INSERT INTO seaorm_mig_t (name) VALUES ('seed-row')")
            .await?;
        Ok(())
    }

    async fn down(&self, manager: &SchemaManager) -> Result<(), DbErr> {
        manager
            .drop_table(Table::drop().table(SeaormMigT::Table).if_exists().to_owned())
            .await?;
        // A 模式定档：identity 附属序列不随 DROP TABLE 级联，down 须显式清理
        manager
            .get_connection()
            .execute_unprepared("DROP SEQUENCE IF EXISTS seaorm_mig_t_id_identity")
            .await?;
        Ok(())
    }
}

pub struct Migrator;

#[async_trait::async_trait]
impl MigratorTrait for Migrator {
    fn migrations() -> Vec<Box<dyn MigrationTrait>> {
        vec![Box::new(Migration)]
    }
}

// ---- 守卫与断言辅助 ----

/// 连接守卫：取 GAUSSDB_PASSWORD；缺失则打印 skip 提示并返回 None（不 panic）。
fn gaussdb_password() -> Option<String> {
    match std::env::var("GAUSSDB_PASSWORD") {
        Ok(pwd) => Some(pwd),
        Err(_) => {
            eprintln!("skipped: GAUSSDB_PASSWORD not set");
            None
        }
    }
}

/// 探针库连接 URL（本地 5432，库 seaorm_survey，用户 appuser）。
fn gaussdb_url(pwd: &str) -> String {
    format!("gaussdb://appuser:{pwd}@localhost:5432/seaorm_survey")
}

/// 表是否存在（information_schema.tables，A 模式可用的标准视图）。
async fn table_exists(db: &sea_orm::DatabaseConnection, table: &str) -> Result<bool, DbErr> {
    let stmt = Statement::from_string(
        DbBackend::GaussDB,
        format!("SELECT COUNT(*) AS n FROM information_schema.tables WHERE table_name = '{table}'"),
    );
    let row = db
        .query_one_raw(stmt)
        .await?
        .ok_or_else(|| DbErr::Custom("information_schema.tables query returned no row".into()))?;
    let n: i64 = row.try_get("", "n")?;
    Ok(n > 0)
}

/// 序列是否存在（pg_class，schema-sync 链路已验证的 pg_* 通路）。
async fn sequence_exists(db: &sea_orm::DatabaseConnection, sequence: &str) -> Result<bool, DbErr> {
    let stmt = Statement::from_string(
        DbBackend::GaussDB,
        format!("SELECT COUNT(*) AS n FROM pg_class WHERE relname = '{sequence}' AND relkind = 'S'"),
    );
    let row = db
        .query_one_raw(stmt)
        .await?
        .ok_or_else(|| DbErr::Custom("pg_class query returned no row".into()))?;
    let n: i64 = row.try_get("", "n")?;
    Ok(n > 0)
}

/// 旅程前后的幂等清理：清表、清 identity 附属序列、清迁移记录
/// （seaql_migrations 可能尚未 install，先探存在再删记录）。
async fn cleanup(db: &sea_orm::DatabaseConnection) -> Result<(), DbErr> {
    db.execute_unprepared("DROP TABLE IF EXISTS seaorm_mig_t")
        .await?;
    db.execute_unprepared("DROP SEQUENCE IF EXISTS seaorm_mig_t_id_identity")
        .await?;
    if table_exists(db, "seaql_migrations").await? {
        let name = Migration.name();
        db.execute_unprepared(&format!(
            "DELETE FROM seaql_migrations WHERE version = '{name}'"
        ))
        .await?;
    }
    Ok(())
}

#[tokio::test]
async fn gaussdb_migration_journey() -> Result<(), DbErr> {
    let Some(pwd) = gaussdb_password() else {
        return Ok(());
    };
    let db = Database::connect(gaussdb_url(&pwd)).await?;
    assert_eq!(db.get_database_backend(), DbBackend::GaussDB);

    // 前置清理：上次运行残留（并行无冲突：表名/序列名/迁移名均唯一）
    cleanup(&db).await?;

    let body = async {
        let name = Migration.name().to_owned();

        // ---- up：全链路（install -> DDL 渲染 -> 初始行 -> 迁移记录） ----
        Migrator::up(&db, None).await?;

        assert!(
            table_exists(&db, "seaorm_mig_t").await?,
            "up 后 seaorm_mig_t 应存在"
        );
        assert!(
            table_exists(&db, "seaql_migrations").await?,
            "install 应创建 seaql_migrations"
        );
        let applied = Migrator::get_applied_migrations(&db).await?;
        assert!(
            applied.iter().any(|m| m.name() == name),
            "seaql_migrations 应记录版本 '{name}'，实际 {:?}",
            applied
                .iter()
                .map(|m| m.name().to_owned())
                .collect::<Vec<_>>()
        );
        let rows = db
            .query_all_raw(Statement::from_string(
                DbBackend::GaussDB,
                "SELECT id, name FROM seaorm_mig_t WHERE name = 'seed-row'".to_owned(),
            ))
            .await?;
        assert_eq!(rows.len(), 1, "up 里的初始行应存在");
        let seed: String = rows[0].try_get("", "name")?;
        assert_eq!(seed, "seed-row");

        // ---- down：DROP TABLE + 补清 identity 序列 + 删迁移记录 ----
        Migrator::down(&db, None).await?;

        assert!(
            !table_exists(&db, "seaorm_mig_t").await?,
            "down 后 seaorm_mig_t 应不存在"
        );
        assert!(
            !sequence_exists(&db, "seaorm_mig_t_id_identity").await?,
            "down 后 identity 附属序列 seaorm_mig_t_id_identity 应已清"
        );
        let applied_after = Migrator::get_applied_migrations(&db).await?;
        assert!(
            !applied_after.iter().any(|m| m.name() == name),
            "down 后迁移记录应删除"
        );

        Ok::<(), DbErr>(())
    }
    .await;

    // 无论 body 成败都清理
    let cleaned = cleanup(&db).await;

    body?;
    cleaned
}
