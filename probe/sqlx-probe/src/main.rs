//! P0 详细版探针：sqlx 0.9 直连 GaussDB 507（A 模式）行为定档
//! 用例：MD5 认证 / server_version / 扩展协议 PL/SQL / IDENTITY / floatvector wire 行为
//! 运行：GAUSSDB_PASSWORD=... cargo run（探针库 seaorm_survey，不碰已有库）

use sqlx::postgres::PgConnectOptions;
use sqlx::{Column, PgPool, Row, TypeInfo};

async fn exec(pool: &PgPool, name: &'static str, sql: &'static str) {
    match sqlx::query(sql).execute(pool).await {
        Ok(r) => println!("[{name}] OK rows={}", r.rows_affected()),
        Err(e) => println!("[{name}] ERR {e}"),
    }
}

#[tokio::main]
async fn main() {
    let pwd = std::env::var("GAUSSDB_PASSWORD").expect("请设置 GAUSSDB_PASSWORD 环境变量");
    let opts = PgConnectOptions::new()
        .host("localhost")
        .port(5432)
        .username("appuser")
        .password(&pwd)
        .database("seaorm_survey");

    let pool = match PgPool::connect_with(opts).await {
        Ok(p) => {
            println!("[1 MD5认证+连接池] OK");
            p
        }
        Err(e) => {
            println!("[1 MD5认证+连接池] ERR {e}");
            return;
        }
    };

    // ---- 2. server_version 假象在 sqlx 连接后的表现 ----
    match sqlx::query_as::<_, (String,)>("SHOW server_version")
        .fetch_one(&pool)
        .await
    {
        Ok((v,)) => println!("[2 server_version] {v}"),
        Err(e) => println!("[2 server_version] ERR {e}"),
    }

    // ---- 3. 扩展协议 PL/SQL 截断复现（对照 psycopg2 simple query 成功的结果）----
    exec(
        &pool,
        "3a 扩展协议 PL/SQL 函数DDL",
        "CREATE OR REPLACE FUNCTION f_sqlx() RETURNS void AS $$ BEGIN NULL; END $$ LANGUAGE plpgsql",
    )
    .await;
    exec(&pool, "3b 调用该函数", "SELECT f_sqlx()").await;

    // ---- 4. IDENTITY（sea-orm 2.0 默认自增形态）----
    exec(
        &pool,
        "4a IDENTITY建表",
        "CREATE TABLE IF NOT EXISTS t_identity (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v varchar(10))",
    )
    .await;
    match sqlx::query("INSERT INTO t_identity (v) VALUES ('x') RETURNING id")
        .fetch_one(&pool)
        .await
    {
        Ok(row) => match row.try_get::<i32, _>(0) {
            Ok(id) => println!("[4b IDENTITY插入+RETURNING] OK id={id} (INT4)"),
            Err(e) => {
                println!("[4b IDENTITY插入+RETURNING] i32直读 ERR {e}");
                match sqlx::query_as::<_, (String,)>(
                    "INSERT INTO t_identity (v) VALUES ('y') RETURNING id::text",
                )
                .fetch_one(&pool)
                .await
                {
                    Ok((s,)) => println!("[4b] id::text 通道 OK id={s}"),
                    Err(e2) => println!("[4b] id::text 通道 ERR {e2}"),
                }
            }
        },
        Err(e) => println!("[4b IDENTITY插入+RETURNING] 执行 ERR {e}"),
    }

    // ---- 5. floatvector wire 行为（OID 4409）----
    // 5a 直查列：看 sqlx 识别的类型名，以及未知 OID 列能否按 String 读
    match sqlx::query("SELECT id, repr FROM vt WHERE id = 1")
        .fetch_one(&pool)
        .await
    {
        Ok(row) => {
            let col = &row.columns()[1];
            println!(
                "[5a floatvector列元信息] col={} type_info.name={}",
                col.name(),
                col.type_info().name()
            );
            match row.try_get::<String, _>(1) {
                Ok(s) => println!("[5a] 直读 String OK: {s}"),
                Err(e) => println!("[5a] 直读 String ERR {e}"),
            }
        }
        Err(e) => println!("[5a] ERR {e}"),
    }
    // 5b ::text cast 读（安全通道）
    match sqlx::query_as::<_, (i32, String)>("SELECT id, repr::text FROM vt WHERE id = 1")
        .fetch_one(&pool)
        .await
    {
        Ok((id, s)) => println!("[5b ::text读] OK id={id} repr={s}"),
        Err(e) => println!("[5b ::text读] ERR {e}"),
    }
    // 5c 文本参数绑定插入（扩展协议，$1 未声明类型 → 服务端按列类型解析）
    match sqlx::query("INSERT INTO vt (id, repr, b) VALUES (2, $1, '[0,1,1]')")
        .bind("[7.5, 8.5, 9.5]")
        .execute(&pool)
        .await
    {
        Ok(r) => println!("[5c 文本绑定插入] OK rows={}", r.rows_affected()),
        Err(e) => println!("[5c 文本绑定插入] ERR {e}"),
    }
    // 5d <-> 距离排序 + 参数绑定（扩展协议下解析 ANN 操作符）
    match sqlx::query_as::<_, (i32,)>("SELECT id FROM vt ORDER BY repr <-> $1 LIMIT 1")
        .bind("[0,0,0]")
        .fetch_one(&pool)
        .await
    {
        Ok((id,)) => println!("[5d <->参数绑定] OK 最近 id={id}"),
        Err(e) => println!("[5d <->参数绑定] ERR {e}"),
    }

    // 5e 显式 cast：文本参数绑定插入（对 5c 失败的对策验证）
    match sqlx::query("INSERT INTO vt (id, repr, b) VALUES (3, $1::floatvector, '[0,0,1]')")
        .bind("[7.5, 8.5, 9.5]")
        .execute(&pool)
        .await
    {
        Ok(r) => println!("[5e $1::floatvector绑定插入] OK rows={}", r.rows_affected()),
        Err(e) => println!("[5e $1::floatvector绑定插入] ERR {e}"),
    }
    // 5f 显式 cast：<-> 距离排序（对 5d 失败的对策验证）
    match sqlx::query_as::<_, (i32,)>(
        "SELECT id FROM vt ORDER BY repr <-> $1::floatvector LIMIT 1",
    )
    .bind("[0,0,0]")
    .fetch_one(&pool)
    .await
    {
        Ok((id,)) => println!("[5f <->$1::floatvector] OK 最近 id={id}"),
        Err(e) => println!("[5f <->$1::floatvector] ERR {e}"),
    }
    // 5g 写读 round-trip
    match sqlx::query_as::<_, (String,)>("SELECT repr::text FROM vt WHERE id = 3")
        .fetch_one(&pool)
        .await
    {
        Ok((s,)) => println!("[5g round-trip] OK id=3 repr={s}"),
        Err(e) => println!("[5g round-trip] ERR {e}"),
    }

    // ---- 6. pg_type 交叉确认 ----
    match sqlx::query_as::<_, (String, String, String)>(
        "SELECT oid::text, typname, typinput::text FROM pg_type WHERE typname = 'floatvector'",
    )
    .fetch_one(&pool)
    .await
    {
        Ok((oid, n, f)) => println!("[6 pg_type] oid={oid} {n} typinput={f}"),
        Err(e) => println!("[6 pg_type] ERR {e}"),
    }

    // ---- T10.1 探针：MigratorTrait 内部 seaql_migrations 链的 opfusion 复现 ----
    println!("=== T10.1 opfusion 精确复现（seaql_migrations 链） ===");
    match sqlx::query_as::<_, (String,)>(
        "SELECT version FROM seaql_migrations ORDER BY version",
    )
    .fetch_all(&pool)
    .await
    {
        Ok(v) => println!("[1] 无参 fetch_all OK: {v:?}"),
        Err(e) => println!("[1] 无参 fetch_all ERR: {e}"),
    }
    match sqlx::query("INSERT INTO seaql_migrations (version) VALUES ($1)")
        .bind("opfusion-probe-1")
        .execute(&pool)
        .await
    {
        Ok(r) => println!("[2] 带参 execute(INSERT) OK rows={}", r.rows_affected()),
        Err(e) => println!("[2] 带参 execute(INSERT) ERR: {e}"),
    }
    match sqlx::query("DELETE FROM seaql_migrations WHERE version = $1")
        .bind("opfusion-probe-1")
        .execute(&pool)
        .await
    {
        Ok(r) => println!("[3] 带参 execute(DELETE) OK rows={}", r.rows_affected()),
        Err(e) => println!("[3] 带参 execute(DELETE) ERR: {e}"),
    }

    pool.close().await;
    println!("=== 探针结束 ===");
}
